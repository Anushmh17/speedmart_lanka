  Future<void> _onVendorCreateAccount(Map<String, String> data) async {
    final email = data['email'] ?? '';
    final fullName = data['fullName'] ?? '';
    final password = data['password'] ?? '';
    final confirmPassword = data['confirmPassword'] ?? '';
    final shopName = data['shopName'] ?? '';
    final categories = data['categories'] ?? '';

    if (fullName.trim().isEmpty) { _showError('Please enter your full name.'); return; }
    final emailErr = Validators.email(email.trim());
    if (emailErr != null) { _showError('Please enter a valid email.'); return; }
    if (password.length < 8) { _showError('Password must be at least 8 characters.'); return; }
    if (password != confirmPassword) { _showError('Passwords do not match.'); return; }
    if (shopName.trim().isEmpty) { _showError('Please enter your shop name.'); return; }
    if (categories.trim().isEmpty) { _showError('Please select at least one category.'); return; }
    final nic = (data['nic'] ?? '').trim().toUpperCase();
    if (nic.isNotEmpty) {
      final nicErr = Validators.nic(nic);
      if (nicErr != null) { _showError(nicErr); return; }
    }

    final lat = double.tryParse(data['latitude'] ?? '');
    final lng = double.tryParse(data['longitude'] ?? '');
    if (lat == null || lng == null) { _showError('Please pin your shop location on the map.'); return; }

    // Store form data and send OTP â€” registration happens after OTP verified
    _pendingVendorRegData = data;
    if (!await _checkOnline()) return;

    setState(() => _isLoading = true);
    try {
      final reg = ref.read(customerRegistrationProvider.notifier);
      reg.setMode(isLogin: false);
      // Vendor phone is a Sri Lanka mobile — ensure registration treats
      // this as an LK phone user so OTP is sent to the phone, not email.
      reg.setLkUser(true);

      final rawPhone = (data['phone'] ?? '').trim();
      debugPrint('[VendorRegister] raw phone input: "$rawPhone"');
      final normalized = SriLankaPhoneHelper.normalizeSriLankaPhoneForStorage(rawPhone);
      debugPrint('[VendorRegister] normalized for storage: "$normalized"');
      reg.updatePhone(rawPhone);

      await reg.sendOtp();
      if (!mounted) return;

      final regState = ref.read(customerRegistrationProvider);
      if (regState.hasError) {
        _showError(regState.error!);
        return;
      }

      _go(_FigmaAuthPage.vendorRegisterOtp);
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  Future<void> _onVendorRegisterOtpSuccess(String otp) async {
    final data = _pendingVendorRegData;
    if (data == null) { _showError('Session expired. Please try again.'); return; }

    final ok = await ref.read(customerRegistrationProvider.notifier).verifyOtp(otp);
    if (!mounted) return;
    if (!ok) {
      final errMsg = ref.read(customerRegistrationProvider).error ?? 'Incorrect OTP. Please try again.';
      _vendorRegisterOtpKey.currentState?.reportError(errMsg);
      _showError(errMsg);
      return;
    }

    setState(() => _isLoading = true);
    try {
      final email = data['email'] ?? '';
      final shopName = data['shopName'] ?? '';
      final categories = data['categories'] ?? '';
      final lat = double.tryParse(data['latitude'] ?? '')!;
      final lng = double.tryParse(data['longitude'] ?? '')!;
      final nic = (data['nic'] ?? '').trim().toUpperCase();

      await ref.read(authProvider.notifier).register(
        fullName: data['fullName']!.trim(),
        email: email.trim(),
        phone: data['phone'] ?? '',
        password: data['password']!,
        role: UserRole.vendor,
        nic: nic.isNotEmpty ? nic : null,
        businessName: shopName.trim(),
        categories: categories.isNotEmpty ? categories.split(',') : null,
        shopName: shopName.trim(),
        shopAddress: data['shopAddress'] ?? '',
        shopProvince: data['province']?.isNotEmpty == true ? data['province'] : null,
        shopDistrict: data['district']?.isNotEmpty == true ? data['district'] : null,
        shopLatitude: lat,
        shopLongitude: lng,
        shopLocationSource: 'map_pin',
        businessRegistrationNumber: data['businessRegNo']?.isNotEmpty == true ? data['businessRegNo'] : null,
        detectedCountry: 'LK',
        detectionSource: 'app_default',
        verifiedPhone: true,
        verifiedEmail: false,
        shopLocationAccuracyMeters: 0,
        shopLocationDetectedAt: DateTime.now(),
      );
      if (!mounted) return;
      final authState = ref.read(authProvider);
      if (authState.hasError) {
        _showError(authState.error!);
      } else if (authState.isAuthenticated) {
        _pendingVendorRegData = null;
        context.go(RouteNames.vendorHome);
      }
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  Future<void> _onVendorRegisterResendOtp() async {
    final phone = _pendingVendorRegData?['phone'] ?? '';
    if (phone.isEmpty) return;
    final reg = ref.read(customerRegistrationProvider.notifier);
    reg.updatePhone(phone);
    await reg.sendOtp();
    if (!mounted) return;
    final state = ref.read(customerRegistrationProvider);
    if (state.hasError) _showError(state.error!);
  }

