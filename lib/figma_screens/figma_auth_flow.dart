  static const _pageOrder = [
    _FigmaAuthPage.customerLogin,
    _FigmaAuthPage.customerLoginOtp,
    _FigmaAuthPage.customerRegister,
    _FigmaAuthPage.customerRegisterOtp,
    _FigmaAuthPage.vendorLogin,
