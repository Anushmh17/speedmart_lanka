    if (state.hasError) _showError(state.error!);
  }

  // â”€â”€ Vendor login â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

  Future<void> _onVendorSignIn(bool rememberMe) async {
    final email = _vendorLoginEmailCtrl.text.trim();
    final password = _vendorLoginPasswordCtrl.text;
    if (email.isEmpty) { _showError('Please enter your email.'); return; }
    if (password.isEmpty) { _showError('Please enter your password.'); return; }
    if (!await _checkOnline()) return;

    setState(() => _isLoading = true);
    try {
      // Read the previously stored flag BEFORE this login
      final wasRemembered = await StorageService.getVendorRememberMe();

      final result = await ref.read(authProvider.notifier).verifyVendorCredentials(
        email: email,
        password: password,
      );
      if (!mounted) return;
      final authState = ref.read(authProvider);
      if (authState.hasError || result == null) {
        _showError(authState.error ?? 'Login failed.');
        return;
      }
      // Skip OTP only if vendor had Remember Me from a PREVIOUS session
      if (rememberMe && wasRemembered) {
        final restored = await ref
            .read(authProvider.notifier)
            .restoreRememberedSession(
              role: UserRole.vendor,
              matchesAccount: (user) =>
                  user.email.toLowerCase() == email.toLowerCase(),
            );
        if (restored) {
          if (mounted) context.go(RouteNames.vendorHome);
          return;
        }
      }
      {
        final reg = ref.read(customerRegistrationProvider.notifier);
        reg.setMode(isLogin: false);
        reg.updatePhone(result.phone);
        await reg.sendOtp();
        if (!mounted) return;
        final regState = ref.read(customerRegistrationProvider);
        if (regState.hasError) { _showError(regState.error!); return; }
        _vendorLoginOtpPhone = regState.maskedContact;
        _pendingVendorRememberMe = rememberMe;
        _go(_FigmaAuthPage.vendorLoginOtp);
      }
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  String _maskEmail(String email) {
    final at = email.indexOf('@');
    if (at <= 1) return email;
    final local = email.substring(0, at);
    final domain = email.substring(at);
    final visible = local.length > 3 ? local.substring(0, 3) : local[0];
    return '$visible***$domain';
  }

