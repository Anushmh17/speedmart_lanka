  // â”€â”€ GPS auto-detect â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

  Future<void> _autoDetectLocation() async {
    setState(() => _isDetectingGps = true);
    try {
      final position = await GpsLocationService().getCurrentPosition();
      final result = await ReverseGeocodingService().reverseGeocode(
        latitude: position.latitude,
        longitude: position.longitude,
      );
      if (!mounted) return;
      if (result.geocodingSucceeded &&
          result.province != null &&
          result.district != null) {
        final province = SriLankaData.provinceByName(result.province!);
        final district = SriLankaData.districtByName(result.district!);
        if (province != null && district != null) {
          setState(() {
            _selectedProvince = province;
            _selectedDistrict = district;
            _detectedLatitude = position.latitude;
            _detectedLongitude = position.longitude;
          });
          ref.read(customerRegistrationProvider.notifier).applyGpsLocation(
                province: province,
                district: district,
                approxArea: result.city ?? '',
                latitude: position.latitude,
                longitude: position.longitude,
                accuracy: result.accuracy,
                detectedAt: result.detectedAt ?? DateTime.now(),
              );
          if (mounted) {
            _showToast('Location detected: ${district.name}, ${province.name}');
          }
          return;
        }
      }
      if (mounted) _showToast('Could not detect location. Please select manually.');
    } on LocationException catch (e) {
      if (mounted) _showToast(e.message, isError: true);
    } catch (_) {
      if (mounted) _showToast('GPS unavailable. Please select manually.', isError: true);
    } finally {
      if (mounted) setState(() => _isDetectingGps = false);
    }
  }

  // â”€â”€ Customer register: validate & send OTP â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

  Future<void> _onSriLankaCustomerCreateAccount(
      Map<String, String> data) async {
    final phone = (data['phone'] ?? '').trim();
    final fullName = (data['fullName'] ?? '').trim();
    final nic = (data['nic'] ?? '').trim();
    final email = (data['email'] ?? '').trim();
    final preciseAddress = (data['preciseAddress'] ?? '').trim();

    final nicErr = Validators.nic(nic);
    if (nicErr != null) { _showError(nicErr); return; }
    if (fullName.isEmpty) { _showError('Please enter your full name.'); return; }
    final phoneErr = SriLankaPhoneHelper.validateSriLankaMobile(phone);
    if (phoneErr != null) { _showError(phoneErr); return; }
    final emailErr = Validators.email(email);
    if (emailErr != null) { _showError(emailErr); return; }
    if (_detectedLatitude == null || _detectedLongitude == null) { _showError('Please pin your delivery location on the map.'); return; }
    if (_selectedProvince == null) { _showError('Please select your Province.'); return; }
    if (_selectedDistrict == null) { _showError('Please select your District.'); return; }
    if (preciseAddress.isEmpty) { _showError('Please enter your precise delivery address.'); return; }
    if (!await _checkOnline()) return;

    setState(() => _isLoading = true);
    try {
      await ref.read(authProvider.notifier).validateCustomerRegistrationData(
        phone: phone.trim(),
        email: (data['email'] ?? '').trim(),
        nic: nic.trim(),
      );

      final reg = ref.read(customerRegistrationProvider.notifier);
      reg.setMode(isLogin: false);
      reg.updateFullName(fullName.trim());
      reg.updatePhone(phone.trim());
      reg.updateNic(nic.trim());
      reg.updatePreciseAddress(preciseAddress.trim());
      reg.updateDeliveryNote(data['deliveryNote'] ?? '');
      reg.updateEmail(data['email'] ?? '');
      reg.updateProvince(_selectedProvince);
      reg.updateDistrict(_selectedDistrict);

      await reg.sendOtp();
      if (!mounted) return;
      final state = ref.read(customerRegistrationProvider);
      if (state.hasError) { _showError(state.error!); return; }
      _go(_FigmaAuthPage.customerRegisterOtp);
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  // â”€â”€ Customer login: send OTP â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

  Future<void> _onSriLankaCustomerSendOtp(bool rememberMe) async {
    final phone = _loginPhoneCtrl.text.trim();
    if (phone.isEmpty) { _showError('Please enter your phone number.'); return; }
    if (!await _checkOnline()) return;

    setState(() => _isLoading = true);
    try {
      final wasRemembered = await StorageService.getCustomerRememberMe();
      final reg = ref.read(customerRegistrationProvider.notifier);
      reg.setMode(isLogin: true);
      reg.updatePhone(phone);

      if (rememberMe && wasRemembered) {
        final phoneDigits = phone.replaceAll(RegExp(r'[^0-9]'), '');
        final restored = await ref
            .read(authProvider.notifier)
            .restoreRememberedSession(
              role: UserRole.customer,
              matchesAccount: (UserModel user) {
                final savedDigits = user.phone.replaceAll(RegExp(r'[^0-9]'), '');
                return phoneDigits.isNotEmpty &&
                    savedDigits.isNotEmpty &&
                    (phoneDigits.endsWith(savedDigits.length > 9
                            ? savedDigits.substring(savedDigits.length - 9)
                            : savedDigits) ||
                        savedDigits.endsWith(phoneDigits.length > 9
                            ? phoneDigits.substring(phoneDigits.length - 9)
                            : phoneDigits));
              },
            );
        if (restored) {
          if (mounted) context.go(RouteNames.customerHome);
          return;
        }
      }

      _pendingCustomerRememberMe = rememberMe;
      await reg.sendOtp();
      if (!mounted) return;
      final state = ref.read(customerRegistrationProvider);
      if (state.hasError) { _showError(state.error!); return; }
      _go(_FigmaAuthPage.customerLoginOtp);
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  // â”€â”€ OTP success handlers â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

  Future<void> _onCustomerLoginOtpSuccess(String otp, {bool rememberMe = false}) async {
    setState(() => _isLoading = true);
    try {
      if (otp.isNotEmpty) {
        // Firebase Phone Auth: verifyOtp signs the user into Firebase Auth directly
        final ok = await ref.read(customerRegistrationProvider.notifier).verifyOtp(otp);
        if (!mounted) return;
        if (!ok) {
          final errMsg = ref.read(customerRegistrationProvider).error ?? 'Incorrect OTP. Please try again.';
          _customerLoginOtpKey.currentState?.reportError(errMsg);
          _showError(errMsg);
          return;
        }
      }
      final regState = ref.read(customerRegistrationProvider);
      final contact = regState.data.primaryContact;
      await ref.read(authProvider.notifier).loginCustomerOtp(contact: contact);
      if (!mounted) return;
      await StorageService.saveCustomerRememberMe(rememberMe);
      if (!rememberMe) await StorageService.clearRememberedSession();
      context.go(RouteNames.customerHome);
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  Future<void> _onCustomerRegisterOtpSuccess(String otp) async {
    setState(() => _isLoading = true);
    try {
      final ok = await ref.read(customerRegistrationProvider.notifier).verifyOtp(otp);
      if (!mounted) return;
      if (!ok) {
        final errMsg = ref.read(customerRegistrationProvider).error ?? 'Incorrect OTP. Please try again.';
        _customerRegisterOtpKey.currentState?.reportError(errMsg);
        _showError(errMsg);
        return;
      }
      final regState = ref.read(customerRegistrationProvider);
      debugPrint('[FigmaAuth] Registering with lat=${regState.data.deliveryLatitude} lng=${regState.data.deliveryLongitude}');
      await ref.read(authProvider.notifier).register(
            fullName: regState.data.fullName,
            email: regState.data.email,
            phone: regState.data.phone,
            password: '',
            role: UserRole.customer,
            nic: regState.data.nic,
            verifiedPhone: true,
            detectedCountry: 'LK',
            detectionSource: 'app_default',
            deliveryProvince: _selectedProvince?.name ?? regState.data.province?.name,
            deliveryDistrict: _selectedDistrict?.name ?? regState.data.district?.name,
            deliveryApproxArea: regState.data.approxArea,
            deliveryPreciseAddress: regState.data.preciseAddress,
            deliveryNote: regState.data.deliveryNote,
            deliveryLatitude: regState.data.deliveryLatitude,
          deliveryLongitude: regState.data.deliveryLongitude,
          );
      if (!mounted) return;
      // Registration has already completed Firebase Phone OTP verification.
      // Treat the first signed-in session as opted in to remember me so logout
      // can offer the customer the choice to skip OTP next time.
      await StorageService.saveCustomerRememberMe(true);
      if (!mounted) return;
      final user = ref.read(currentUserProvider);
      if (user != null) {
        final defaultAddress = CustomerDeliveryAddress.fromUserFields(
          customerId: user.id,
          deliveryProvince: _selectedProvince?.name ?? regState.data.province?.name,
          deliveryDistrict: _selectedDistrict?.name ?? regState.data.district?.name,
          deliveryApproxArea: regState.data.approxArea,
          deliveryPreciseAddress: regState.data.preciseAddress,
          deliveryNote: regState.data.deliveryNote,
          accuracy: regState.data.deliveryAccuracy,
          detectedAt: regState.data.deliveryDetectedAt,
          deliveryLatitude: regState.data.deliveryLatitude,
          deliveryLongitude: regState.data.deliveryLongitude,
          isGpsDetected: regState.data.deliveryLatitude != null &&
              regState.data.deliveryLongitude != null,
          isManualOverride: false,
        );
        await ref.read(customerDeliveryAddressProvider.notifier).saveDefaultAddress(defaultAddress);
      }
      if (!mounted) return;
      context.go(RouteNames.customerHome);
    } catch (e) {
      if (mounted) _showError(e.toString().replaceAll('Exception: ', ''));
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  // â”€â”€ OTP resend handlers â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

