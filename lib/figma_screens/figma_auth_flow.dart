  static Future<void> _hideNavBar() async {
    try {
      await const MethodChannel('com.speedmart.lk/system_ui').invokeMethod('hideNavBar');
    } catch (_) {}
  }

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
    WidgetsBinding.instance.addPostFrameCallback((_) => _hideNavBar());
    _animCtrl = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 340),
    );
    // Build direction-aware animations once using a curved parent
    final curved = CurvedAnimation(parent: _animCtrl, curve: Curves.easeInOutCubic);
    _inSlide = _DirectionalTween(
      dirNotifier: _dirNotifier,
      inbound: true,
    ).animate(curved);
    _outSlide = _DirectionalTween(
      dirNotifier: _dirNotifier,
      inbound: false,
    ).animate(curved);
    _animCtrl.value = 1.0;
    _page = widget.role == FigmaAuthRole.customer
        ? _FigmaAuthPage.customerLogin
        : _FigmaAuthPage.vendorLogin;
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _animCtrl.dispose();
    _loginPhoneCtrl.dispose();
    _vendorLoginEmailCtrl.dispose();
    _vendorLoginPasswordCtrl.dispose();
    _forgotPasswordEmailCtrl.dispose();
    _newPasswordCtrl.dispose();
    _confirmNewPasswordCtrl.dispose();
    super.dispose();
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed) _hideNavBar();
  }

  @override
  Future<bool> didPopRoute() async {
    if (_isHandlingBack) return true;
    _isHandlingBack = true;
    try {
      final allow = await _onWillPop();
      if (allow && mounted) {
        SystemNavigator.pop();
      }
    } finally {
      _isHandlingBack = false;
    }
    return true;
  }



  void _go(_FigmaAuthPage page, {bool back = false, bool postFrame = false}) {
    if (!mounted) return;
    if (postFrame) {
      WidgetsBinding.instance.addPostFrameCallback((_) => _go(page, back: back));
      return;
    }
    FocusScope.of(context).unfocus();
    final currentIdx = _pageOrder.indexOf(_page);
    final nextIdx = _pageOrder.indexOf(page);
    final goingBack = back || (nextIdx < currentIdx);
    _dirNotifier.value = goingBack ? -1.0 : 1.0;
    setState(() {
      _prevPage = _page;
      _page = page;
    });
    _animCtrl.forward(from: 0.0);
  }

